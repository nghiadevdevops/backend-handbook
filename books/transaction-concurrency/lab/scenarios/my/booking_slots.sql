-- @setup
DROP TABLE IF EXISTS slot; CREATE TABLE slot(room INT, hr INT, booking_id INT, PRIMARY KEY(room,hr)) ENGINE=InnoDB;
-- @a
SET TRANSACTION ISOLATION LEVEL __LEVEL__; START TRANSACTION;
SELECT COUNT(*) INTO @c FROM slot WHERE room=1 AND hr IN (10,11);
DO SLEEP(5);
INSERT INTO slot VALUES (1,10,1),(1,11,1);
COMMIT;
-- @b
DO SLEEP(1.5);
SET TRANSACTION ISOLATION LEVEL __LEVEL__; START TRANSACTION;
SELECT COUNT(*) INTO @c FROM slot WHERE room=1 AND hr IN (9,10);
DO SLEEP(1);
INSERT INTO slot VALUES (1,9,2),(1,10,2);
COMMIT;
-- @final
