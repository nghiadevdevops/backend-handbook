-- @setup
DROP TABLE IF EXISTS booking; CREATE TABLE booking(id INT AUTO_INCREMENT PRIMARY KEY, room INT, s INT, e INT, KEY(room)) ENGINE=InnoDB;
-- @a
SET TRANSACTION ISOLATION LEVEL __LEVEL__; START TRANSACTION;
SELECT COUNT(*) INTO @c FROM booking WHERE room=1 AND s < 12 AND e > 10;
DO SLEEP(5);
INSERT INTO booking(room,s,e) SELECT 1,10,12 FROM DUAL WHERE @c=0;
COMMIT;
-- @b
DO SLEEP(1.5);
SET TRANSACTION ISOLATION LEVEL __LEVEL__; START TRANSACTION;
SELECT COUNT(*) INTO @c FROM booking WHERE room=1 AND s < 11 AND e > 9;
DO SLEEP(1);
INSERT INTO booking(room,s,e) SELECT 1,9,11 FROM DUAL WHERE @c=0;
COMMIT;
-- @final
