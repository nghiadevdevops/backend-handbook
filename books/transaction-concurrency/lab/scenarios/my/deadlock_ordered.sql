-- @setup
DROP TABLE IF EXISTS acct; CREATE TABLE acct(id INT PRIMARY KEY, bal INT) ENGINE=InnoDB; INSERT INTO acct VALUES (1,100),(2,100);
-- @a
SET TRANSACTION ISOLATION LEVEL __LEVEL__; START TRANSACTION;
SELECT id FROM acct WHERE id IN (1,2) ORDER BY id FOR UPDATE;
DO SLEEP(3);
UPDATE acct SET bal=bal-10 WHERE id=1;
UPDATE acct SET bal=bal+10 WHERE id=2;
COMMIT;
-- @b
DO SLEEP(1);
SET TRANSACTION ISOLATION LEVEL __LEVEL__; START TRANSACTION;
SELECT id FROM acct WHERE id IN (1,2) ORDER BY id FOR UPDATE;
UPDATE acct SET bal=bal-10 WHERE id=2;
UPDATE acct SET bal=bal+10 WHERE id=1;
COMMIT;
-- @final
SELECT 'tổng tiền (kỳ vọng 200)', SUM(bal) FROM acct;
SELECT IF(SUM(bal)=200,'ANOMALY:no','ANOMALY:yes') FROM acct;
